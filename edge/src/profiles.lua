--- Record that `device` is on the current profile, so the next driver version
--- can tell which version it has to move it from.
function profiles.remember(device, name)
  if type(device) ~= "table" or type(device.set_field) ~= "function" then
    return nil
  end
  name = name or profiles.current()
  fields.set(device, fields.PROFILE_NAME, name)
  return name
end

-- Devices this driver run has already looked at. One attempt per device per
-- driver lifetime: `added` and `init` both call `ensure`, and a hub that
-- refuses the update must not be asked again in a loop.
local attempted = {}

-- The loop guard of the profile moves (`ensure`, `apply_battery`), two maps
-- per driver run.
--
-- `switched` is the profile this run last moved each device to. It stands in
-- for `name_of` afterwards: a move fires `infoChanged`, and on a hub that is
-- slow to (or never does) put the new name on `device.profile`, `name_of`
-- would still read the old one.
--
-- `refused` is the target the hub last turned down; it is not asked for
-- again in one run. The next driver start asks again.
local switched = {}
local refused = {}

local function attempt_key(device)
  local id = device.id
  if type(id) == "string" and id ~= "" then
    return id
  end
  return device
end

--- The profile name this driver run believes `device` is on: the one it last
--- moved it to, else what the device says (`name_of`).
function profiles.current_name(device)
  if type(device) ~= "table" then
    return nil
  end
  return switched[attempt_key(device)] or profiles.name_of(device)
end

--- Move `device` onto the current profile if it is due (§6.6).
--
-- Returns the new profile name, or nil when nothing was done. Called from
-- `init` and `added`; only the first call per device does anything.
function profiles.ensure(device)
  if type(device) ~= "table" then
    return nil
  end
  local key = attempt_key(device)
  if attempted[key] then
    return nil
  end
  attempted[key] = true

  local name = profiles.name_of(device)
  -- #107: a v1 device lands on the current profile. Whether it has a battery is only known once a status has said so (#116:
  -- `fields.HAS_BATTERY`, which a v1 device never wrote), so it lands on the plain
  -- one and the first statuses move a laptop on (`apply_battery`). A v2 device
  -- keeps its battery half (`migration_for`).
  local target = profiles.migration_for(name, profiles.has_battery(device))
  if not target then
    -- Nothing to do, but keep the field in step with reality when the device
    -- is already on a current profile.
    if profiles.is_current(name) then
      profiles.remember(device, name)
    end
    return nil
  end

  local ok, err = pcall(function()
    return device:try_update_metadata({ profile = target })
  end)
  if not ok then
    logger().warn(string.format("could not migrate %s to %s: %s",
      tostring(device.id), target, tostring(err)))
    return nil
  end
  profiles.remember(device, target)
  -- #107: from here on this run reads the new name, whatever the hub still
  -- reports on `device.profile` - an icon switch right after a migration must
  -- start from the new name, not from the old one it would refuse to touch.
  switched[key] = target
  logger().info(string.format("migrated %s to %s", tostring(device.id), target))
  return target
end

-- #116: consecutive statuses that disagreed with the device's profile about
-- the battery, per device: `{ present = bool, count = n }`.
local battery_votes = {}

-- #116: how many statuses in a row have to say the same thing before the
-- device changes profile. One odd reading (a flaky `GetSystemPowerStatus`, a
-- service that restarted into its "no battery yet" placeholder) must not cost
-- the user a profile switch and a repaint each way.
profiles.BATTERY_VOTES = 2

--- #116: whether the last settled status said this PC has a battery (the
--- persisted `fields.HAS_BATTERY`), false when none has.
function profiles.has_battery(device)
  return fields.get(device, fields.HAS_BATTERY) == true
end

local function remember_battery(device, present)
  if profiles.has_battery(device) ~= present then
    fields.set(device, fields.HAS_BATTERY, present)
  end
end

--- #116: move `device` between the plain and the `-battery` profile when
--- the status disagrees with the one it is on.
--
-- Returns the new profile name, or nil when nothing was done. Called after
-- every status (poll and push) with `status.battery.present`. Only after
-- `BATTERY_VOTES` consecutive statuses agree on the other answer does it ask
-- for the switch - one each way at most per real change. A device that is
-- not on a current profile is left to `ensure`. The answer is
-- persisted (`fields.HAS_BATTERY`) so the next migration lands on the right side.
function profiles.apply_battery(device, present)
  if type(device) ~= "table" then
    return nil
  end
  present = present == true
  local key = attempt_key(device)
  local name = profiles.current_name(device)
  local on_battery = profiles.battery_of(name)
  if on_battery == nil then
    battery_votes[key] = nil
    return nil
  end
  if on_battery == present then
    battery_votes[key] = nil
    remember_battery(device, present)
    return nil
  end
  local votes = battery_votes[key]
  if votes and votes.present == present then
    votes.count = votes.count + 1
  else
    votes = { present = present, count = 1 }
    battery_votes[key] = votes
  end
  if votes.count < profiles.BATTERY_VOTES then
    return nil
  end
  local target = profiles.for_battery(present)
  if refused[key] == target then
    return nil
  end
  local ok, err = pcall(function()
    return device:try_update_metadata({ profile = target })
  end)
  if not ok then
    refused[key] = target
    logger().warn(string.format("could not switch %s to %s: %s",
      tostring(device.id), target, tostring(err)))
    return nil
  end
  battery_votes[key] = nil
  switched[key] = target
  refused[key] = nil
  profiles.remember(device, target)
  remember_battery(device, present)
  logger().info(string.format("switched %s from %s to %s (battery %s)",
    tostring(device.id), name, target, present and "present" or "absent"))
  return target
end

-- Devices this driver run has already tried to delete, for the same reason
-- `attempted` exists: `init` fires more than once per device, and every PC's
-- `init` walks the device list.
local removed = {}

--- Delete one leftover child (`is_child`), once per device per driver run.
--
-- Returns true when the delete was asked for now. `driver:try_delete_device`
-- is the API (lua_libs st/driver.lua; there is no device method); it answers
-- `nil, "<why>"` on a hub without the feature and may raise. A failure is
-- logged once and the child stays - it does nothing any more (its lifecycle
-- is ignored, nothing is emitted on it), and the user can delete it in the app.
function profiles.remove_child(driver, device)
  if not profiles.is_child(device) then
    return false
  end
  local key = attempt_key(device)
  if removed[key] then
    return false
  end
  removed[key] = true

  local what = tostring(device.parent_assigned_child_key or profiles.name_of(device))
  logger().info(string.format("removing leftover child %s (%s)", tostring(device.id), what))
  local ok, result, why = pcall(function() return driver:try_delete_device(device.id) end)
  if not ok or (result == nil and why ~= nil) then
    logger().warn(string.format("could not delete leftover child %s (%s): %s",
      tostring(device.id), what, tostring(ok and why or result)))
  end
  return true
end

--- Delete every leftover child among the driver's devices (`remove_child`).
--- Called from a PC's `init` and `added`. Returns how many were asked for.
function profiles.remove_children(driver)
  local ok, devices = pcall(function() return driver:get_devices() end)
  if not ok or type(devices) ~= "table" then
    return 0
  end
  local count = 0
  for _, device in ipairs(devices) do
    if profiles.remove_child(driver, device) then
      count = count + 1
    end
  end
  return count
end

--- Forget the one-attempt-per-device guards (tests only).
function profiles.reset()
  attempted = {}
  removed = {}
  switched = {}
  refused = {}
  battery_votes = {}
end

return profiles
