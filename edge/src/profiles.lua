
-- Profile names and the migration between their versions (design doc §6.6).
--
-- A device's screen is fixed by the presentations at creation time; only a
-- profile with a new name regenerates it (platform notes "프로필과 화면 생성").
-- So every screen change bumps the generation (`VERSION`, `pc.vN`): the
-- older published files stay in the package for the devices still on them,
-- and `ensure` moves each device on its first `init` after the update.
--
-- Four names per generation since #160 (v16), `pc[-watch][-battery].vN`:
-- one per set of the two cards a PC may not need - the watch list (#123)
-- and the battery (#116) - each only where the PC's status says it has that
-- feature (`apply_cards`). All in the Switch category, the one that gives
-- the app's own "change icon" option. v15 (#158, Dev channel only) had eight,
-- with a third card, the monitor (#153, `pc-monitor-….v15`); v13 and v14 had
-- two names (the battery twin, #136); v1 to v12 had the `iconStyle`
-- preference (#100) as an axis: ten categories, one profile each, the names
-- `pc-<style>[-battery].vN` that `KNOWN` still lists. The files are
-- generated by tools/gen-profiles.js. A migration keeps the cards the old
-- profile had unless this driver has settled them (`stored_cards`); the
-- style and the monitor card it drops.
--
-- Everything here is pure except `remember`, `ensure`,
-- `apply_cards`, `remove_child` and `remove_children`, which touch the
-- device or the driver, and all of them are guarded: a hub that refuses
-- `try_update_metadata` or `try_delete_device` must not take the lifecycle
-- handler down with it.

local fields = require "device.fields"

local profiles = {}

-- The profile generation every current name carries (`pc.v16`, …).
-- 14: the PC app v1.3.0 cards (#151-#154). 15: #158 - main down to seven
-- capabilities, the cards `media`, `presence` and `actions`, the monitor and
-- watch cards only on the variants that have them. 16: #160 - no monitor
-- card and no audio device switching; the `sound` card (pcSpeaker, pcMic)
-- after `media`.
profiles.VERSION = 16

-- #136: the category of every current profile. The app's own "change icon"
-- option exists only for a few categories with an icon set (Switch,
-- SmartPlug, Light, sensors, …) - not Others, not SmartMonitor (tried in
-- v11) - so the driver no longer picks icons (`iconStyle`, #100): the user
-- does, in the app. main's first capability is a switch (on = WoL, off =
-- the off action), so the category is also true.
profiles.CATEGORY = "Switch"

-- #136: the style the bare name of each generation stands for, from v12 on
-- the only one there is. Up to v10 others, v11 (Dev channel only) monitor.
-- Why `pc-monitor.v10` exists but `pc-others.v10` does not.
-- `{ before = generation, style = default }`, oldest first.
profiles.DEFAULT_STYLE = "switch"
profiles.PAST_DEFAULTS = {
  { before = 11, style = "others" },
  { before = 12, style = "monitor" },
}

--- #136: the style the bare name of generation `version` stands for.
function profiles.default_style_at(version)
  for _, past in ipairs(profiles.PAST_DEFAULTS) do
    if version < past.before then
      return past.style
    end
  end
  return profiles.DEFAULT_STYLE
end

-- #100: the `iconStyle` values of v1 to v12 and the category each of their
-- profiles declared. Only for the names of those generations (`KNOWN`) and
-- the tests of the frozen files now.
profiles.STYLES = {
  "switch", "monitor", "others", "plug", "tv",
  "projector", "network", "hub", "theater", "remote",
}
profiles.CATEGORIES = {
  others = "Others",
  monitor = "SmartMonitor",
  switch = "Switch",
  plug = "SmartPlug",
  tv = "Television",
  projector = "Projector",
  network = "Networking",
  hub = "Hub",
  theater = "HomeTheater",
  remote = "RemoteController",
}

--- The profile name for one style and battery choice at `version`:
--- `pc.v10`, `pc-tv.v10`, `pc-battery.v10`, `pc-tv-battery.v10`. The
--- style the bare name stands for is the default of that generation (#136):
--- `pc.v10` is Others, `pc.v11` SmartMonitor, `pc.v12` on Switch. From
--- v13 there is no style: `name_for(nil, battery)`.
function profiles.name_for(style, battery, version)
  version = version or profiles.VERSION
  local default = profiles.default_style_at(version)
  local name = "pc"
  if style ~= nil and style ~= default then
    name = name .. "-" .. style
  end
  if battery == true then
    name = name .. "-battery"
  end
  return string.format("%s.v%d", name, version)
end

-- #158/#160: the cards a current name may or may not have, in name order. A
-- set of them is `{ watch = bool, battery = bool }`.
profiles.AXES = { "watch", "battery" }

-- #160: the axes of the generations after the styled ones (`LAST_STYLED_VERSION`)
-- and before this one: the battery twin in v13 and v14 (#136), the monitor
-- card, the watch list and the battery in v15 (#158).
profiles.PAST_AXES = {
  [13] = { "battery" },
  [14] = { "battery" },
  [15] = { "monitor", "watch", "battery" },
}

--- The axes of generation `version` (default: this one).
function profiles.axes_at(version)
  version = version or profiles.VERSION
  if version == profiles.VERSION then
    return profiles.AXES
  end
  return profiles.PAST_AXES[version]
end

--- #158: the profile of generation `version` (default: the current one)
--- with exactly the cards `cards` says: `pc.v16`, `pc-watch.v16`,
--- `pc-watch-battery.v16`, `pc-monitor-watch.v15`, … A card the generation
--- has no axis for is left out.
function profiles.for_cards(cards, version)
  cards = cards or {}
  version = version or profiles.VERSION
  local name = "pc"
  for _, axis in ipairs(profiles.axes_at(version) or {}) do
    if cards[axis] == true then
      name = name .. "-" .. axis
    end
  end
  return string.format("%s.v%d", name, version)
end

--- #160: every name of a generation that has axes (v13 on), in name order -
--- the first axis the most significant: `pc.v16`, `pc-battery.v16`,
--- `pc-watch.v16`, `pc-watch-battery.v16`.
function profiles.names_at(version)
  local axes = profiles.axes_at(version) or {}
  local out = {}
  for bits = 0, (1 << #axes) - 1 do
    local cards = {}
    for i, axis in ipairs(axes) do
      cards[axis] = (bits & (1 << (#axes - i))) ~= 0
    end
    out[#out + 1] = profiles.for_cards(cards, version)
  end
  return out
end

-- What new devices are created with: neither card. A status moves the
-- device onto the cards it needs (#116, #158).
profiles.PC = profiles.for_cards({})

-- #107: the battery twin of `PC`.
profiles.BATTERY = profiles.for_cards({ battery = true })

-- Every name a device may sit on without being migrated, all four. A set,
-- `CURRENT[name] == true`, and the list in name order.
profiles.CURRENT = {}
profiles.CURRENT_NAMES = profiles.names_at(profiles.VERSION)
for _, name in ipairs(profiles.CURRENT_NAMES) do
  profiles.CURRENT[name] = true
end

-- The last generation that had the ten icon styles (#100); from the next one
-- on, a generation has two names (#136), v15 eight (#158), from v16 four
-- (#160).
profiles.LAST_STYLED_VERSION = 12

-- Every profile name this driver has ever shipped, oldest first. A name that
-- is not in here belongs to another driver, or to a version newer than this
-- one, and is left alone. #107: the ten v1 names (the default and the nine
-- icon variants of #100), then twenty names per generation up to v12 (every
-- style with and without the battery, #116), then the names of each later
-- generation's axes (`names_at`): two for v13 and v14 (#136), eight for v15
-- (#158), the current four last.
profiles.KNOWN = {}
for _, style in ipairs(profiles.STYLES) do
  profiles.KNOWN[#profiles.KNOWN + 1] = profiles.name_for(style, false, 1)
end
for version = 2, profiles.VERSION do
  if version <= profiles.LAST_STYLED_VERSION then
    for _, battery in ipairs({ false, true }) do
      for _, style in ipairs(profiles.STYLES) do
        profiles.KNOWN[#profiles.KNOWN + 1] = profiles.name_for(style, battery, version)
      end
    end
  else
    for _, name in ipairs(profiles.names_at(version)) do
      profiles.KNOWN[#profiles.KNOWN + 1] = name
    end
  end
end

-- Generations that only ever lived on the Dev channel. Their names stay in
-- KNOWN so a development device still on one migrates, but their files are
-- not packaged: the package limit is 655360 bytes.
profiles.UNSHIPPED_VERSIONS = {
  [2] = true, [3] = true, [4] = true, [5] = true, [6] = true, [7] = true, [8] = true, [9] = true,
  -- #136: the SmartMonitor default and the Switch default, Dev channel only.
  [11] = true, [12] = true,
  -- #158: the PC app v1.3.0 cards all on every device, Dev channel only.
  [14] = true,
  -- #160: the eight variants with the monitor card, Dev channel only.
  [15] = true,
}

--- True when the package carries a file for this profile name.
function profiles.is_shipped(name)
  local version = tonumber(tostring(name or ""):match("%.v(%d+)$"))
  return version ~= nil and not profiles.UNSHIPPED_VERSIONS[version]
end

-- What a device with neither a name nor `fields.PROFILE_NAME` is assumed to be
-- on: the oldest name this driver ever created a device with.
profiles.LEGACY = "pc.v1"

-- This driver creates no child device any more. Two kinds may be left on a
-- development hub, neither with a profile in the package, and both are
-- deleted (`remove_child`): #81's display child (`pc-display.vN`, key
-- "display") and #123's app children (`pc-app.v1`, keyed by process name),
-- which the watch card's slots replaced before anything was published.
profiles.CHILD_PREFIXES = { "pc-display", "pc-app." }

local function logger()
  local ok, log = pcall(require, "log")
  if ok then
    return log
  end
  local noop = function() end
  return { trace = noop, debug = noop, info = noop, warn = noop, error = noop }
end

--------------------------------------------------------------------------------
-- pure
--------------------------------------------------------------------------------

--- The profile a device is created with now.
function profiles.current()
  return profiles.PC
end

--- Every profile name this driver has shipped.
function profiles.known()
  return profiles.KNOWN
end

--- True when `name` is one of the profiles a device is created on or moved
--- between now - one of the four (`CURRENT`).
function profiles.is_current(name)
  if type(name) ~= "string" or name == "" then
    return false
  end
  return profiles.CURRENT[name] == true
end

--- #158: the cards of a profile name, `{ watch, battery }`. A current name
--- says them itself (`pc-watch-battery.v16`), and so does a v15 one
--- (`pc-monitor-watch.v15`; #160: its monitor card has no axis any more);
--- an older name has what its generation had - the watch card from v7 to
--- v14 (component `apps`), the battery on a `-battery` name. nil for a name
--- of no generation.
function profiles.cards_of(name)
  if type(name) ~= "string" then
    return nil
  end
  local stem, version = name:match("^(.-)%.v(%d+)$")
  version = tonumber(version)
  if not version then
    return nil
  end
  local battery = stem:match("%-battery$") ~= nil
  if version < 15 then
    return { watch = version >= 7 and version <= 14, battery = battery }
  end
  return {
    watch = stem:find("-watch", 1, true) ~= nil,
    battery = battery,
  }
end

--- The profile `device_profile_name` has to move to, or nil.
--
-- nil covers all three "do nothing" cases: already current, not a name this
-- driver ever used (foreign device, or a version from
-- the future), and no name at all. A child profile name is not ours to
-- migrate either: no such series is packaged any more, and such a device is deleted
-- instead (`is_child`). A known older name lands on the current profile -
-- its icon style is gone (#136: the user picks the icon in the app).
-- @param stored #158: what this driver's statuses settled, `{ watch,
--   battery }` (`stored_cards`; nil = never settled). A settled watch answer
--   wins; an unsettled one keeps the card the old profile had (`cards_of`) -
--   a routine may read the watch slots of a v13 device, so its card stays
--   until two statuses say the PC does not use it. #160: a v15 name's
--   monitor card is dropped (`pc-monitor-watch.v15` lands on `pc-watch.v16`).
--   The battery card goes by the name OR the field (#107): a `-battery` name
--   got there on two statuses that agreed (#116), which is better evidence
--   than a field a single odd status may not have written; the v1 names
--   never had one, so there only the field says "yes".
function profiles.migration_for(device_profile_name, stored)
  if type(device_profile_name) ~= "string" or device_profile_name == "" then
    return nil
  end
  if profiles.is_current(device_profile_name) then
    return nil
  end
  stored = type(stored) == "table" and stored or {}
  for _, known in ipairs(profiles.known()) do
    if device_profile_name == known then
      local had = profiles.cards_of(device_profile_name) or {}
      local function settled(axis)
        if type(stored[axis]) == "boolean" then
          return stored[axis]
        end
        return had[axis] == true
      end
      return profiles.for_cards({
        watch = settled("watch"),
        battery = stored.battery == true or had.battery == true,
      })
    end
  end
  return nil
end


--- True when `name` is the profile of a child device an older build created
--- (`CHILD_PREFIXES`).
function profiles.is_child_profile(name)
  if type(name) ~= "string" then
    return false
  end
  for _, prefix in ipairs(profiles.CHILD_PREFIXES) do
    if name:sub(1, #prefix) == prefix then
      return true
    end
  end
  return false
end

--- True when `device` is a leftover child device (see `CHILD_PREFIXES`).
--
-- Two independent marks, because a hub may only carry one of them: a
-- `parent_assigned_child_key` (only an EDGE_CHILD has one, and this driver
-- creates none any more), and a profile name from a child series.
function profiles.is_child(device)
  if type(device) ~= "table" then
    return false
  end
  local key = device.parent_assigned_child_key
  if type(key) == "string" and key ~= "" then
    return true
  end
  return profiles.is_child_profile(profiles.name_of(device))
end

--------------------------------------------------------------------------------
-- reading the name off a device
--------------------------------------------------------------------------------

local function stored_name(device)
  if type(device) ~= "table" or type(device.get_field) ~= "function" then
    return nil
  end
  local value = fields.get(device, fields.PROFILE_NAME)
  if type(value) == "string" and value ~= "" then
    return value
  end
  return nil
end

--- The profile name of `device`.
--
-- The Edge API exposes `device.profile` as a table of `id` and `components`;
-- the *name* is there on some firmwares only, so it wins when present and the
-- field written at creation time (and after every migration) is the fallback.
-- A device with neither predates #79 and is therefore on v1.
function profiles.name_of(device)
  local profile = (device or {}).profile
  if type(profile) == "table" and type(profile.name) == "string" and profile.name ~= "" then
    return profile.name
  end
  if type(profile) == "string" and profile ~= "" then
    return profile
  end
  return stored_name(device) or profiles.LEGACY
end

