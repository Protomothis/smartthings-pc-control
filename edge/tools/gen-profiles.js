#!/usr/bin/env node
/*
 * Generate the current device profiles from tools/profile-template.yml (#107).
 *
 *   cd edge && bun tools/gen-profiles.js           # (re)write profiles/*
 *   cd edge && bun tools/gen-profiles.js --check   # exit 1 if any file is stale
 *   cd edge && bun tools/gen-profiles.js --media-component
 *        # #118: the alternative layout - the media group (audioTrackData,
 *        # mediaPlayback, mediaTrackControl, audioVolume, audioMute) moves out
 *        # of main into a component `media`. For packaging a Dev channel build
 *        # to compare the two screens; do not commit its output (the sync test
 *        # fails on purpose), run the plain command again afterwards.
 *
 * `node` works the same. One template, twenty files: every `iconStyle` value
 * (#100 - a category is fixed per profile, and the category is the icon) with
 * and without the `battery` component (#116 - a desktop must not carry an
 * empty battery card). Names and files:
 *
 *   pc.v8            profiles/pc-v8.yml             others, no battery
 *   pc-tv.v8         profiles/pc-tv-v8.yml          tv, no battery
 *   pc-battery.v8    profiles/pc-battery-v8.yml     others, battery
 *   pc-tv-battery.v8 profiles/pc-tv-battery-v8.yml  tv, battery
 *
 * The rules are deliberately small; `--check` (CI: npm run check-profiles)
 * fails when a file on disk is not what they produce:
 *
 *   1. Normalise line endings to LF and drop the template's header - every
 *      line before the first one that starts with `name:`.
 *   2. Replace `__NAME__` and `__CATEGORY__` (each exactly once).
 *   3. Keep the lines between `# @battery-begin` and `# @battery-end` only for
 *      a battery profile; drop the two marker lines always.
 *   3b. (#118) The lines between `# @media-begin` and `# @media-end` stay where
 *      they are by default; with --media-component they move, under a
 *      `- id: media` component header, to the `# @media-component` line. The
 *      three marker lines are dropped either way.
 *   3c. (#129) Drop every other comment line (`#` after optional spaces): the
 *      template explains itself, the twenty copies do not need to.
 *   4. Prepend the generated header below.
 *
 * The style list and the categories are also in src/profiles.lua
 * (`STYLES`, `CATEGORIES`); the Lua test walks that list, so the two cannot
 * drift apart without the suite failing.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const EDGE = path.resolve(__dirname, '..');
const TEMPLATE = path.join(EDGE, 'tools', 'profile-template.yml');
const OUT_DIR = path.join(EDGE, 'profiles');

// The profile generation. A screen change bumps this AND the name in
// src/profiles.lua (`profiles.VERSION`); the files of the old generation then
// stay in profiles/ untouched, for the devices that have not moved yet -
// unless that generation was never published (`profiles.UNSHIPPED_VERSIONS`),
// in which case its files are deleted instead.
// 3: pcMessage replaced the standard notification/speechSynthesis pair.
// 4: pcNotify (send only) replaced pcMessage; v2 and v3 were never published.
// 5: pcToast (send + lastMessage, the row's value) replaced pcNotify; v4 was
//    never published either.
// 6: pcApps (a summary row; one child device per watched app, #123) replaced
//    the kind-based pcActivity; v5 was never published either.
// 7: the watch card - component `apps` with pcWatch (summary, names, five
//    slots a routine reads) replaced pcApps and the per-app child devices;
//    v6 was never published either.
// 8: the watch card's preview - the main view shows a component card's first
//    three state rows side by side, so the slots come before `names` and
//    their values are short ("실행 중", not "실행 중 (Running)"); v7 was
//    never published either.
// 9: no screen change - the capability presentation of pcWatch was updated
//    seconds before v8 was packaged, and v8's device presentation was built
//    from the old one; a fresh name regenerates it. v8 was never published
//    either.
const VERSION = 9;

const DEFAULT_STYLE = 'others';

// [iconStyle, category], in the order the preference lists them.
const STYLES = [
  ['others', 'Others'],
  ['monitor', 'SmartMonitor'],
  ['switch', 'Switch'],
  ['plug', 'SmartPlug'],
  ['tv', 'Television'],
  ['projector', 'Projector'],
  ['network', 'Networking'],
  ['hub', 'Hub'],
  ['theater', 'HomeTheater'],
  ['remote', 'RemoteController'],
];

function profileName(style, battery) {
  let name = 'pc';
  if (style !== DEFAULT_STYLE) name += '-' + style;
  if (battery) name += '-battery';
  return name + '.v' + VERSION;
}

// pc.v3 -> pc-v3.yml, pc-tv-battery.v3 -> pc-tv-battery-v3.yml
function fileName(name) {
  return name.replace(/\.v(\d+)$/, '-v$1') + '.yml';
}

function header(style, battery, mediaComponent) {
  return [
    '# GENERATED by tools/gen-profiles.js from tools/profile-template.yml - do not edit.',
    '# iconStyle: ' + style + ' · battery component: ' + (battery ? 'yes' : 'no')
      + ' · media group: ' + (mediaComponent ? 'component media' : 'main'),
  ].join('\n') + '\n';
}

// #118: the component the media group becomes with --media-component.
const MEDIA_COMPONENT = ['  - id: media', '    label: 미디어', '    capabilities:'];

function replaceOnce(text, placeholder, value) {
  const parts = text.split(placeholder);
  if (parts.length !== 2) {
    throw new Error('the template must contain ' + placeholder + ' exactly once, found ' + (parts.length - 1));
  }
  return parts.join(value);
}

function render(template, style, category, battery, mediaComponent) {
  const lines = template.replace(/\r\n/g, '\n').split('\n');
  const first = lines.findIndex((line) => line.startsWith('name:'));
  if (first < 0) throw new Error('the template has no `name:` line');

  const out = [];
  const media = [];
  let inBattery = false;
  let inMedia = false;
  let mediaAt = -1;
  for (const line of lines.slice(first)) {
    if (line === '# @battery-begin') {
      inBattery = true;
    } else if (line === '# @battery-end') {
      inBattery = false;
    } else if (line === '# @media-begin') {
      inMedia = true;
    } else if (line === '# @media-end') {
      inMedia = false;
    } else if (line === '# @media-component') {
      mediaAt = out.length;
    } else if (/^\s*#/.test(line)) {
      // a template comment
    } else if (inBattery && !battery) {
      // not a battery profile
    } else if (inMedia && mediaComponent) {
      media.push(line);
    } else {
      out.push(line);
    }
  }
  if (inBattery) throw new Error('# @battery-begin without # @battery-end');
  if (inMedia) throw new Error('# @media-begin without # @media-end');
  if (mediaComponent) {
    if (mediaAt < 0) throw new Error('the template has no # @media-component line');
    out.splice(mediaAt, 0, ...MEDIA_COMPONENT, ...media);
  }

  let body = out.join('\n');
  body = replaceOnce(body, '__NAME__', profileName(style, battery));
  body = replaceOnce(body, '__CATEGORY__', category);
  return header(style, battery, mediaComponent) + body;
}

function main() {
  const check = process.argv.includes('--check');
  // #118: the alternative layout, for a Dev channel comparison only. The
  // committed files are the default (media group in main), which is what
  // --check holds them to (tests/profilegen_test.lua checks the layout rules).
  const mediaComponent = process.argv.includes('--media-component');
  if (check && mediaComponent) {
    process.stderr.write('--check verifies the committed (default) layout; drop --media-component\n');
    process.exit(2);
  }
  const template = fs.readFileSync(TEMPLATE, 'utf8');
  const stale = [];
  let written = 0;

  for (const battery of [false, true]) {
    for (const [style, category] of STYLES) {
      const file = path.join(OUT_DIR, fileName(profileName(style, battery)));
      const text = render(template, style, category, battery, mediaComponent);
      let current = null;
      try {
        current = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
      } catch (e) {
        current = null;
      }
      if (current === text) continue;
      if (check) {
        stale.push(path.relative(EDGE, file));
      } else {
        fs.writeFileSync(file, text);
        written++;
      }
    }
  }

  if (check) {
    if (stale.length > 0) {
      process.stderr.write('stale generated profiles (run `bun tools/gen-profiles.js`):\n  ' + stale.join('\n  ') + '\n');
      process.exit(1);
    }
    process.stdout.write('profiles are in sync with tools/profile-template.yml\n');
    return;
  }
  process.stdout.write('wrote ' + written + ' of ' + STYLES.length * 2 + ' profiles'
    + (mediaComponent ? ' with the media group in component `media` - do not commit these' : '') + '\n');
}

main();
