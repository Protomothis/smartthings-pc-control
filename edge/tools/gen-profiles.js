#!/usr/bin/env node
/*
 * Generate the current device profiles from tools/profile-template.yml (#107).
 *
 *   cd edge && bun tools/gen-profiles.js           # (re)write profiles/*
 *   cd edge && bun tools/gen-profiles.js --check   # exit 1 if any file is stale
 *
 * `node` works the same. One template, twenty files: every `iconStyle` value
 * (#100 - a category is fixed per profile, and the category is the icon) with
 * and without the `battery` component (#116 - a desktop must not carry an
 * empty battery card). Names and files:
 *
 *   pc.v2            profiles/pc-v2.yml             others, no battery
 *   pc-tv.v2         profiles/pc-tv-v2.yml          tv, no battery
 *   pc-battery.v2    profiles/pc-battery-v2.yml     others, battery
 *   pc-tv-battery.v2 profiles/pc-tv-battery-v2.yml  tv, battery
 *
 * The rules are deliberately small, because tests/profilegen_test.lua applies
 * the same ones in Lua and compares the result with the files on disk:
 *
 *   1. Normalise line endings to LF and drop the template's header - every
 *      line before the first one that starts with `name:`.
 *   2. Replace `__NAME__` and `__CATEGORY__` (each exactly once).
 *   3. Keep the lines between `# @battery-begin` and `# @battery-end` only for
 *      a battery profile; drop the two marker lines always.
 *   4. Prepend the generated header below.
 *
 * The style list and the categories are also in src/profiles.lua
 * (`STYLES`, `CATEGORIES`); the Lua test walks that list, so the two cannot
 * drift apart without the suite failing.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const EDGE = path.resolve(__dirname, '..');
const TEMPLATE = path.join(EDGE, 'tools', 'profile-template.yml');
const OUT_DIR = path.join(EDGE, 'profiles');

// The profile generation. A future screen change bumps this AND the name in
// src/profiles.lua (`profiles.VERSION`); the files of the old generation then
// stay in profiles/ untouched, for the devices that have not moved yet.
const VERSION = 2;

const DEFAULT_STYLE = 'others';

// [iconStyle, category], in the order the preference lists them.
const STYLES = [
  ['others', 'Others'],
  ['monitor', 'SmartMonitor'],
  ['switch', 'Switch'],
  ['plug', 'SmartPlug'],
  ['tv', 'Television'],
  ['projector', 'Projector'],
  ['network', 'Networking'],
  ['hub', 'Hub'],
  ['theater', 'HomeTheater'],
  ['remote', 'RemoteController'],
];

function profileName(style, battery) {
  let name = 'pc';
  if (style !== DEFAULT_STYLE) name += '-' + style;
  if (battery) name += '-battery';
  return name + '.v' + VERSION;
}

// pc.v2 -> pc-v2.yml, pc-tv-battery.v2 -> pc-tv-battery-v2.yml
function fileName(name) {
  return name.replace(/\.v(\d+)$/, '-v$1') + '.yml';
}

function header(style, battery) {
  return [
    '# GENERATED by tools/gen-profiles.js from tools/profile-template.yml - do not edit.',
    '# Change the template and run `bun tools/gen-profiles.js`; tests/profilegen_test.lua',
    '# fails while this file differs from what the template makes.',
    '# iconStyle: ' + style + ' · battery component: ' + (battery ? 'yes' : 'no'),
  ].join('\n') + '\n';
}

function replaceOnce(text, placeholder, value) {
  const parts = text.split(placeholder);
  if (parts.length !== 2) {
    throw new Error('the template must contain ' + placeholder + ' exactly once, found ' + (parts.length - 1));
  }
  return parts.join(value);
}

function render(template, style, category, battery) {
  const lines = template.replace(/\r\n/g, '\n').split('\n');
  const first = lines.findIndex((line) => line.startsWith('name:'));
  if (first < 0) throw new Error('the template has no `name:` line');

  const out = [];
  let inBattery = false;
  for (const line of lines.slice(first)) {
    if (line === '# @battery-begin') {
      inBattery = true;
    } else if (line === '# @battery-end') {
      inBattery = false;
    } else if (!inBattery || battery) {
      out.push(line);
    }
  }
  if (inBattery) throw new Error('# @battery-begin without # @battery-end');

  let body = out.join('\n');
  body = replaceOnce(body, '__NAME__', profileName(style, battery));
  body = replaceOnce(body, '__CATEGORY__', category);
  return header(style, battery) + body;
}

function main() {
  const check = process.argv.includes('--check');
  const template = fs.readFileSync(TEMPLATE, 'utf8');
  const stale = [];
  let written = 0;

  for (const battery of [false, true]) {
    for (const [style, category] of STYLES) {
      const file = path.join(OUT_DIR, fileName(profileName(style, battery)));
      const text = render(template, style, category, battery);
      let current = null;
      try {
        current = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
      } catch (e) {
        current = null;
      }
      if (current === text) continue;
      if (check) {
        stale.push(path.relative(EDGE, file));
      } else {
        fs.writeFileSync(file, text);
        written++;
      }
    }
  }

  if (check) {
    if (stale.length > 0) {
      process.stderr.write('stale generated profiles (run `bun tools/gen-profiles.js`):\n  ' + stale.join('\n  ') + '\n');
      process.exit(1);
    }
    process.stdout.write('profiles are in sync with tools/profile-template.yml\n');
    return;
  }
  process.stdout.write('wrote ' + written + ' of ' + STYLES.length * 2 + ' profiles\n');
}

main();
